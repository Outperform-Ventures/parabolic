import {test, expect} from "@playwright/test";
import {resolve} from "node:path";
import {createApp} from "../../src/server/app";
test.use({serviceWorkers:"block"});

test("native issue-summary tabs filter the current view, preserve full totals and share estimate display without hiding Insights", async ({page})=>{
  test.setTimeout(90000);page.setDefaultTimeout(15000);
  await page.setViewportSize({width:1777,height:991});
  let releaseAuth:(()=>void)|undefined;
  const app=createApp({databasePath:":memory:",port:0,staticDir:resolve("dist")}), {url}=await app.start(), errors:string[]=[];
  page.on("pageerror",error=>errors.push(error.message));
  try {
    await page.request.post(url+"/auth/setup",{data:{email:"summary@example.test",password:"isolated-summary-password",name:"Summary owner",workspaceName:"Summary workspace"}});
    const state=await (await page.request.get(url+"/api/v1/state")).json(), team=state.teams[0], status=state.statuses.find((row:any)=>row.teamId===team.id&&row.type==="unstarted"), owner=state.users[0];
    const create=async(kind:string,data:any)=>{const response=await page.request.post(url+"/api/v1/"+kind,{data});expect(response.ok(),await response.text()).toBeTruthy();return response.json()};
    const project=await create("projects",{name:"Summary project",teamIds:[team.id]}), red=await create("labels",{name:"Red",color:"#ef4444"}),blue=await create("labels",{name:"Blue",color:"#3b82f6"});
    const first=await create("issues",{title:"Summary first",teamId:team.id,statusId:status.id,projectId:project.id,assigneeId:owner.id,priority:2,estimate:3,labelIds:[red.id,blue.id]});
    const second=await create("issues",{title:"Summary second",teamId:team.id,statusId:status.id,projectId:project.id,priority:4,estimate:2,labelIds:[red.id]});
    await create("issues",{title:"Summary third",teamId:team.id,statusId:status.id,projectId:project.id,assigneeId:owner.id,priority:2,estimate:5,labelIds:[blue.id]});
    await create("issues",{title:"Outside summary project",teamId:team.id,statusId:status.id,priority:1,estimate:13});
    await page.goto(url+"/project/"+project.id+"/issues");
    const rows=page.locator(".issue-list-scroll [data-issue-id]"), panel=page.getByRole("complementary",{name:"Issue summary",exact:true});
    await expect(rows).toHaveCount(3);
    await page.mouse.move(10,10);
    const projectBadge=rows.first().locator('.issue-project-badge'),beforeHover=await projectBadge.boundingBox();
    await rows.first().hover();
    expect((await projectBadge.boundingBox())!.x).toBe(beforeHover!.x);
    await expect(rows.first().locator('.row-actions')).toHaveCount(0);
    await page.getByRole("button",{name:"Open details",exact:true}).click();
    await expect(panel).toBeVisible();
    await expect(panel).toHaveCSS('width','440px');
    await expect(panel.locator('.view-summary-row').first()).toHaveCSS('height','42px');
    await expect(panel.locator('.view-summary-row').first()).toHaveCSS('padding','0px 10px');
    await expect(panel.locator('.view-summary-rows')).toHaveCSS('padding-top','8px');
    await expect(page.getByRole("complementary",{name:"Project details",exact:true})).toHaveCount(0);
    await expect(panel.getByRole("tab")).toHaveCount(4);
    await panel.getByRole("button",{name:"Filter by No assignee",exact:true}).click();
    await expect(rows).toHaveCount(1);await expect(rows).toHaveAttribute("data-issue-id",second.id);
    await panel.getByRole("tab",{name:"Priority",exact:true}).click();
    await expect(rows).toHaveCount(3);
    await expect(panel.getByRole("button",{name:"High: 2 issues. Show estimates",exact:true})).toBeVisible();
    await expect(panel.locator('.view-summary-filter')).toHaveText(['High','Low']);
    await expect(panel.locator('.priority-icon')).toHaveCount(2);
    await panel.getByRole("button",{name:"Filter by High",exact:true}).click();await expect(rows).toHaveCount(2);
    await expect(page.locator(".issue-summary-filter-notice")).toContainText("1 issue hidden by filters");
    const notice=page.locator('.issue-summary-filter-notice');
    expect((await notice.boundingBox())!.y).toBeGreaterThanOrEqual((await rows.last().boundingBox())!.y+(await rows.last().boundingBox())!.height);
    await expect(notice).toHaveCSS('min-height','84px');
    await expect(notice.getByRole('button',{name:'Clear Filters',exact:true})).toHaveCSS('height','24px');
    await panel.getByRole("button",{name:"High: 2 issues. Show estimates",exact:true}).click();
    await expect(panel.getByRole("button",{name:"High: 8 estimate points. Show issue counts",exact:true})).toBeVisible();
    await expect(page.locator('.group-header[data-group-id="'+status.id+'"] .group-count')).toContainText("8 / 10");
    await panel.getByRole("tab",{name:"Labels",exact:true}).click();await expect(rows).toHaveCount(3);
    await panel.getByRole("button",{name:"Filter by Red",exact:true}).click();await expect(rows).toHaveCount(2);
    await expect(page.locator('.issue-list-scroll [data-issue-id="'+first.id+'"]')).toBeVisible();
    await panel.getByRole("tab",{name:"Labels",exact:true}).focus();await page.keyboard.press("ArrowRight");
    await expect(panel.getByRole("tab",{name:"Priority",exact:true})).toBeFocused();await expect(rows).toHaveCount(3);
    await page.getByRole("button",{name:"Toggle insights",exact:true}).click();
    await expect(panel).toHaveCount(0);await expect(page.getByRole("complementary",{name:"View insights",exact:true})).toBeVisible();
    await page.getByRole("button",{name:"Open details",exact:true}).click();await expect(panel).toBeVisible();
    await expect(page.getByRole("complementary",{name:"View insights",exact:true})).toHaveCount(0);
    await page.screenshot({path:"artifacts/verification/view-summary.png"});
    const authGate=new Promise<void>(resolve=>{releaseAuth=resolve});
    await page.route("**/auth/status",async route=>{await authGate;await route.continue()});
    await page.goto(url+"/team/"+team.id+"/all");await expect(rows).toHaveCount(4);
    await page.keyboard.press("]");await expect(panel).toBeVisible();
    const connected=page.waitForResponse(response=>response.url().startsWith(url+"/api/v1/events"));
    releaseAuth!();await connected;await page.unroute("**/auth/status");await expect(panel).toBeVisible();
    await page.setViewportSize({width:760,height:620});
    const bounds=await panel.boundingBox(), contentBounds=await page.locator(".issue-view-content").boundingBox();
    expect(bounds!.y).toBeGreaterThanOrEqual(contentBounds!.y);
    expect(bounds!.x).toBeGreaterThanOrEqual(contentBounds!.x);
    await panel.getByRole("tab",{name:"Projects",exact:true}).click();await panel.getByRole("button",{name:"Filter by No project",exact:true}).click();await expect(rows).toHaveCount(1);
    await page.getByRole("button",{name:"Close details",exact:true}).click();await expect(rows).toHaveCount(4);await expect(panel).toHaveCount(0);
    await page.reload();await expect(rows).toHaveCount(4);expect(errors).toEqual([]);
  } finally {releaseAuth?.();await page.close();await app.close()}
});
