import {test,expect} from '@playwright/test';
import {createApp} from '../../src/server/app';
import {resolve} from 'node:path';

test('issue filtering, hover shortcuts, checkbox ranges and drop placement work together',async({page})=>{
 const app=createApp({databasePath:':memory:',port:0,staticDir:resolve('dist')});
 const {url}=await app.start();
 try {
  await page.request.post(url+'/auth/setup',{data:{name:'Issue owner',email:'issues@example.test',password:'isolated-issue-test',workspaceName:'Issue review'}});
  const state=await (await page.request.get(url+'/api/v1/state')).json();
  const team=state.teams[0],status=state.statuses.find((s:any)=>s.teamId===team.id&&s.type==='backlog');
  for(let i=0;i<5;i++)await page.request.post(url+'/api/v1/issues',{data:{title:'Interaction '+i,teamId:team.id,statusId:status.id,priority:i<3?2:3,sortOrder:i*100}});
  await page.goto(url+'/team/'+team.id+'/all');
  const rows=page.getByTestId('issue-row');
  await expect(rows).toHaveCount(5);
  await rows.nth(1).hover();await page.keyboard.press('x');
  await expect(rows.nth(1)).toHaveAttribute('aria-selected','true');
  await rows.nth(3).locator('.row-checkbox').click({modifiers:['Shift']});
  await expect(page.locator('.issue-row.selected')).toHaveCount(3);
  await page.keyboard.press('Escape');await expect(page.locator('.issue-row.selected')).toHaveCount(0);
  await page.keyboard.press('f');
  await page.getByRole('menuitem',{name:'Priority',exact:true}).click();
  await page.getByRole('menuitem',{name:'High',exact:true}).click();
  await expect(rows).toHaveCount(3);
  await page.getByRole('button',{name:'High',exact:true}).click();
  await page.getByRole('menuitem',{name:'Medium',exact:true}).click();
  await expect(rows).toHaveCount(5);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Remove Priority filter'}).click();
  await expect(rows).toHaveCount(5);
  await page.getByRole('button',{name:'Display options',exact:true}).click();
  await page.getByLabel('Ordering',{exact:true}).selectOption('title');
  await page.getByRole('button',{name:'Direction',exact:true}).click();
  await page.keyboard.press('Escape');
  await expect(rows.first()).toContainText('Interaction 4');
  await page.getByRole('button',{name:'Display options',exact:true}).click();
  await page.getByLabel('Ordering',{exact:true}).selectOption('sortOrder');
  await page.keyboard.press('Escape');
  const firstId=await rows.first().getAttribute('data-issue-id');
  const last=rows.last(),box=await last.boundingBox();
  await rows.first().dragTo(last,{targetPosition:{x:100,y:box!.height-2}});
  await expect(rows.last()).toHaveAttribute('data-issue-id',firstId!);
  await page.getByRole('button',{name:'Display options',exact:true}).click();
  await page.getByLabel('Ordering',{exact:true}).selectOption('priority');
  await page.getByRole('button',{name:'Advanced sorting and display',exact:true}).click();
  await page.getByRole('button',{name:'Add sort rule',exact:true}).click();
  await page.getByLabel('Sort field 2',{exact:true}).selectOption('title');
  await page.keyboard.press('Escape');
  await expect(rows.first()).toContainText('Interaction 2');
  await page.getByRole('button',{name:'Display options',exact:true}).click();
  await page.getByRole('button',{name:'Advanced sorting and display',exact:true}).click();
  await page.getByRole('button',{name:'Move sort rule 2 up',exact:true}).click();
  await page.getByRole('button',{name:'Save order',exact:true}).click();
  await expect.poll(async()=>{const saved=await(await page.request.get(url+'/api/v1/state')).json();return saved.teams[0].displayDefaults?.all?.sortRules}).toEqual([{field:'priority',direction:'asc'}]);
  await page.keyboard.press('Escape');
  await expect(rows.first()).toContainText('Interaction 4');
  await page.reload();await expect(rows.first()).toContainText('Interaction 4');
  await rows.first().dragTo(rows.last());
  await expect(rows.first()).toContainText('Interaction 4');
 } finally {await app.close();}
});
